#!/usr/bin/env node
// recon — one-shot product fact sheet. Usage: recon <site-url> [github-url] [--app <dapp-url>] [--json]
// Runs site crawl (headless Chromium + read-only fake wallet), GitHub stats, and on-chain address checks in parallel.
// The fake wallet NEVER signs: any tx/signature the dApp requests is captured and rejected.
const { chromium } = require('playwright');
const fs = require('fs');

const argv = process.argv.slice(2);
const flag = (f) => { const i = argv.indexOf(f); if (i < 0) return null; const v = argv[i + 1]; argv.splice(i, 2); return v; };
const APP = flag('--app'); const JSON_OUT = argv.includes('--json'); if (JSON_OUT) argv.splice(argv.indexOf('--json'), 1);
const SITE = argv[0]; const GH = argv.find((a) => /github\.com/.test(a) && a !== SITE);
if (!SITE) { console.error('usage: recon <site-url> [github-url] [--app <dapp-url>] [--json]'); process.exit(1); }

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';
const CHAINS = {
  eth: { id: 1, rpc: 'https://ethereum-rpc.publicnode.com', exp: 'https://etherscan.io/address/' },
  base: { id: 8453, rpc: 'https://mainnet.base.org', exp: 'https://basescan.org/address/' },
  rh: { id: 4663, rpc: 'https://rpc.mainnet.chain.robinhood.com', exp: 'https://robinhoodchain.blockscout.com/address/' },
};
let WALLET = '0x5e1f0000000000000000000000000000000dd0dd'; // dummy read-only address
try { const k = fs.readFileSync('/dev/shm/dd-burner/evm', 'utf8').trim(); if (k) WALLET = require('child_process').execSync(`$HOME/.foundry/bin/cast wallet address --private-key ${k}`).toString().trim(); } catch {}

const t0 = Date.now(); const ms = () => ((Date.now() - t0) / 1000).toFixed(1) + 's';
const rpc = async (url, method, params) => {
  const r = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json', 'user-agent': UA }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }), signal: AbortSignal.timeout(8000) });
  return (await r.json()).result;
};

// ---------------- fingerprints ----------------
const BUILDERS = { 'lovable': /lovable\.(dev|app)|gpteng/i, 'v0/vercel-template': /v0\.dev|generated by v0/i, 'bolt.new': /bolt\.new|stackblitz/i,
  'framer (no-code)': /framerusercontent|framer\.com\/m\//i, 'webflow (no-code)': /webflow\.(com|io)|data-wf-page/i, 'wix': /wixstatic|wix\.com/i,
  'carrd': /carrd\.co/i, 'gitbook': /gitbook/i, 'replit': /replit\.(dev|app)/i, 'base44': /base44/i, 'next.js': /_next\/static/, 'vite': /\/assets\/index-[\w-]+\.js/ };
const WEB3 = { wagmi: /wagmi/i, rainbowkit: /rainbowkit|rainbow-me/i, 'web3modal/reown': /web3modal|reown|walletconnect/i, thirdweb: /thirdweb/i,
  privy: /privy\.io|@privy-io/i, dynamic: /dynamic\.xyz|dynamicauth/i, ethers: /ethers\.js|ethers\/lib|"ethers"/i, viem: /viem/i,
  'solana-wallet-adapter': /wallet-adapter|@solana\/web3/i, jupiter: /jup\.ag|jupiter/i, '0x/1inch/paraswap': /0x\.org|1inch|paraswap/i, lifi: /li\.fi|lifi/i,
  openai: /api\.openai\.com|openai/i, anthropic: /api\.anthropic\.com/i, supabase: /supabase\.co/i, firebase: /firebaseio|firebaseapp/i };
const FAKE = [ [/Math\.random\(\)\s*\*\s*\d+[^;]{0,60}(apy|apr|tvl|price|balance|profit|volume|users)/i, 'Math.random() driving APY/TVL/price/balance'],
  [/(apy|apr|tvl|totalValueLocked|profit)["']?\s*[:=]\s*["']?\d{2,}/i, 'hardcoded APY/TVL/profit literal'],
  [/\b(mock(Data|Api|Response)|fakeData|dummyData|placeholderData)\b/, 'mock/fake data identifiers'],
  [/lorem ipsum/i, 'lorem ipsum filler'], [/setTimeout\([^)]{0,80}(success|confirmed|completed|tx|hash)/i, 'setTimeout faking a success/tx state'],
  [/0x0{40}/, 'zero address literal'], [/(coming soon|under construction|beta access|join waitlist)/i, 'coming-soon / waitlist wording'] ];

async function crawl(url, label) {
  const out = { label, url, ok: false, title: '', hosts: {}, apis: new Set(), rpcCalls: [], walletReq: [], txRequests: [], consoleErr: [], links: new Set(), text: '', addrs: new Set(), builders: new Set(), web3: new Set(), fake: new Set(), bundleBytes: 0, chainIdsSeen: new Set() };
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  try {
    const ctx = await browser.newContext({ userAgent: UA, viewport: { width: 1366, height: 900 } });
    // read-only EIP-1193 provider + EIP-6963 announce. Reads go to the dApp's own RPC via our proxy; writes are captured & rejected.
    await ctx.exposeBinding('__ddReq', async (_s, m, p) => {
      out.walletReq.push(m);
      if (/sendTransaction|sign|Permit|ApprovalForAll|watchAsset|addEthereumChain|switchEthereumChain/i.test(m)) {
        if (/sendTransaction|sign/i.test(m)) out.txRequests.push({ method: m, params: p });
        if (/switchEthereumChain|addEthereumChain/.test(m)) { try { out.chainIdsSeen.add(parseInt(p[0].chainId, 16)); } catch {} return { __ok: null }; }
        return { __err: 'User rejected (dd read-only wallet)' };
      }
      if (m === 'eth_requestAccounts' || m === 'eth_accounts') return { __ok: [WALLET] };
      if (m === 'eth_chainId') return { __ok: '0x' + (global.__chain || 1).toString(16) };
      if (m === 'net_version') return { __ok: String(global.__chain || 1) };
      if (m === 'wallet_getPermissions' || m === 'wallet_requestPermissions') return { __ok: [{ parentCapability: 'eth_accounts' }] };
      const c = Object.values(CHAINS).find((x) => x.id === (global.__chain || 1)) || CHAINS.eth;
      try { if (m === 'eth_call') out.rpcCalls.push({ to: p?.[0]?.to, data: (p?.[0]?.data || '').slice(0, 10) }); return { __ok: await rpc(c.rpc, m, p) }; } catch (e) { return { __err: String(e) }; }
    });
    await ctx.addInitScript((addr) => {
      const listeners = {};
      const req = async ({ method, params }) => { const r = await window.__ddReq(method, params || []); if (r.__err) { const e = new Error(r.__err); e.code = 4001; throw e; } return r.__ok; };
      const provider = { isMetaMask: true, request: req, on: (e, f) => ((listeners[e] ||= []).push(f), provider), removeListener: () => provider, selectedAddress: addr, chainId: '0x1',
        enable: () => req({ method: 'eth_requestAccounts' }), send: (m, p) => req(typeof m === 'string' ? { method: m, params: p } : m), sendAsync: (pl, cb) => req(pl).then((r) => cb(null, { id: pl.id, jsonrpc: '2.0', result: r }), cb) };
      window.ethereum = provider;
      const info = { uuid: 'dd-0000-read-only', name: 'MetaMask', icon: 'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg"/>', rdns: 'io.metamask' };
      const announce = () => window.dispatchEvent(new CustomEvent('eip6963:announceProvider', { detail: Object.freeze({ info, provider }) }));
      window.addEventListener('eip6963:requestProvider', announce); announce();
    }, WALLET);
    const page = await ctx.newPage();
    const bodies = [];
    page.on('console', (m) => m.type() === 'error' && out.consoleErr.length < 15 && out.consoleErr.push(m.text().slice(0, 200)));
    page.on('response', async (r) => {
      const u = new URL(r.url()); out.hosts[u.host] = (out.hosts[u.host] || 0) + 1;
      const ct = r.headers()['content-type'] || '';
      if (/json/.test(ct) && !/\.(js|css)$/.test(u.pathname)) out.apis.add(`${r.request().method()} ${r.status()} ${u.host}${u.pathname}`.slice(0, 160));
      if (r.request().method() === 'POST') { try { const b = JSON.parse(r.request().postData() || '{}'); for (const x of [].concat(b)) if (x?.method?.startsWith?.('eth_') || x?.method?.startsWith?.('get')) { out.rpcCalls.push({ host: u.host, m: x.method, to: x.params?.[0]?.to }); } } catch {} }
      if (/javascript|html|json/.test(ct)) { try { const t = await r.text(); out.bundleBytes += t.length; bodies.push(t); } catch {} }
    });
    const resp = await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30000 });
    out.status = resp?.status();
    await page.waitForLoadState('networkidle', { timeout: 12000 }).catch(() => {});
    // try to connect: click a Connect button, then the injected/MetaMask option
    for (const re of [/connect( wallet)?|launch app|sign in/i, /metamask|browser wallet|injected/i]) {
      const b = page.getByRole('button', { name: re }).first();
      if (await b.isVisible().catch(() => false)) { await b.click({ timeout: 3000 }).catch(() => {}); await page.waitForTimeout(2500); }
    }
    await page.waitForLoadState('networkidle', { timeout: 8000 }).catch(() => {});
    out.title = await page.title();
    out.text = (await page.evaluate(() => document.body?.innerText || '')).replace(/\s+/g, ' ').slice(0, 4000);
    for (const a of await page.$$eval('a[href]', (as) => as.map((a) => a.href))) out.links.add(a);
    await page.screenshot({ path: `/tmp/claude-0/recon-${label}.png` }).catch(() => {});
    const all = bodies.join('\n') + '\n' + (await page.content());
    out.addrFreq = {}; for (const m of all.matchAll(/\b0x[a-fA-F0-9]{40}\b/g)) { const a = m[0].toLowerCase(); out.addrFreq[a] = (out.addrFreq[a] || 0) + 1; }
    out.addrs = new Set(Object.keys(out.addrFreq));
    const html = (await page.content()) + ' ' + Object.keys(out.hosts).join(' ');
    for (const [k, re] of Object.entries(BUILDERS)) if (re.test(html)) out.builders.add(k);
    for (const [k, re] of Object.entries(WEB3)) if (re.test(all)) out.web3.add(k);
    for (const [re, why] of FAKE) { const m = all.match(re); if (m) out.fake.add(`${why}: «${m[0].slice(0, 90)}»`); }
    for (const m of all.matchAll(/chainId["']?\s*[:=]\s*(\d{1,7})\b/g)) out.chainIdsSeen.add(+m[1]);
    out.ok = true;
  } catch (e) { out.error = String(e).slice(0, 300); } finally { await browser.close(); }
  return out;
}

async function github(url) {
  if (!url) return null;
  const m = url.match(/github\.com\/([^/]+)(?:\/([^/#?]+))?/); if (!m) return { error: 'bad url' };
  const H = { 'user-agent': 'dd-recon', accept: 'application/vnd.github+json' };
  const gj = async (p) => { const r = await fetch('https://api.github.com' + p, { headers: H }); return r.ok ? r.json() : { __status: r.status }; };
  const owner = m[1]; let repos = m[2] ? [m[2].replace(/\.git$/, '')] : null;
  if (!repos) { const list = await gj(`/users/${owner}/repos?per_page=100&sort=pushed`); repos = Array.isArray(list) ? list.map((r) => r.name) : []; }
  const res = { owner, repos: [] };
  for (const name of repos.slice(0, 6)) {
    const [meta, langs, contrib, commits] = await Promise.all([gj(`/repos/${owner}/${name}`), gj(`/repos/${owner}/${name}/languages`), gj(`/repos/${owner}/${name}/contributors?per_page=100&anon=1`), gj(`/repos/${owner}/${name}/commits?per_page=100`)]);
    if (meta.__status) { res.repos.push({ name, error: meta.__status }); continue; }
    const tree = await gj(`/repos/${owner}/${name}/git/trees/${meta.default_branch}?recursive=1`);
    const files = (tree.tree || []).filter((f) => f.type === 'blob').map((f) => f.path);
    const cm = Array.isArray(commits) ? commits : [];
    res.repos.push({ name, fork: meta.fork, parent: meta.parent?.full_name, created: meta.created_at?.slice(0, 10), pushed: meta.pushed_at?.slice(0, 10), stars: meta.stargazers_count, desc: meta.description,
      langs: Object.entries(langs).map(([k, v]) => `${k}:${Math.round(v / 1024)}k`).join(' '), contributors: Array.isArray(contrib) ? contrib.map((c) => `${c.login || c.name}(${c.contributions})`).slice(0, 8).join(' ') : '?',
      commitsShown: cm.length, firstShown: cm.at(-1)?.commit?.author?.date?.slice(0, 10), lastCommit: cm[0]?.commit?.author?.date?.slice(0, 10),
      commitMsgs: cm.slice(0, 6).map((c) => c.commit.message.split('\n')[0].slice(0, 70)),
      files: files.length, truncated: tree.truncated, contracts: files.filter((f) => /\.(sol|vy|move)$|programs\/.*\.rs$/.test(f)).slice(0, 25),
      tests: files.filter((f) => /(^|\/)(test|tests|__tests__|spec)\/|\.t\.sol$|\.test\.|\.spec\./.test(f)).length,
      hasBackend: files.some((f) => /(server|api|backend|worker)\//.test(f)), readmeFiles: files.filter((f) => /readme/i.test(f)).length, sampleFiles: files.slice(0, 40) });
  }
  return res;
}

async function checkAddrs(addrs) {
  const out = [];
  await Promise.all([...addrs].slice(0, 40).map(async (a) => {
    const row = { a, on: [] };
    await Promise.all(Object.entries(CHAINS).map(async ([k, c]) => {
      try { const code = await rpc(c.rpc, 'eth_getCode', [a, 'latest']); if (code && code !== '0x') {
        let sym = ''; try { const r = await rpc(c.rpc, 'eth_call', [{ to: a, data: '0x95d89b41' }, 'latest']); if (r && r.length > 130) sym = Buffer.from(r.slice(130).replace(/(00)+$/, ''), 'hex').toString().replace(/[^\x20-\x7e]/g, ''); } catch {}
        row.on.push(`${k}(${(code.length - 2) / 2}b${sym ? ' ' + sym : ''})`); } } catch {}
    }));
    out.push(row);
  }));
  return out;
}

(async () => {
  const [site, app, gh] = await Promise.all([crawl(SITE, 'site'), APP ? crawl(APP, 'app') : null, github(GH)]);
  // auto-discover an app link + github link from the site if not given
  const links = [...site.links];
  const ghFound = [...new Set(links.filter((l) => /github\.com\/[^/]+/.test(l)).map((l) => l.split('#')[0]))];
  const appFound = links.filter((l) => /\/\/app\.|launch|\/app\b|dapp/i.test(l)).slice(0, 3);
  const addrs = new Set([...site.addrs, ...(app?.addrs || [])]);
  const called = new Set([site, app].filter(Boolean).flatMap((s) => s.rpcCalls.map((c) => (c.to || '').toLowerCase()).filter(Boolean)));
  const freq = {}; [site, app].filter(Boolean).forEach((s) => Object.entries(s.addrFreq || {}).forEach(([a, n]) => (freq[a] = (freq[a] || 0) + n)));
  const ranked = [...addrs].filter((a) => !/^0x(0{40}|e{40}|f{40})$|^0x4200000000000000000000000000000000000/.test(a)).sort((a, b) => (called.has(b) - called.has(a)) || (freq[b] - freq[a]));
  const onchain = await checkAddrs(ranked.slice(0, 40)); onchain.forEach((r) => { r.called = called.has(r.a); r.freq = freq[r.a]; });
  const ghAddrHits = gh ? null : null;
  const report = { elapsed: ms(), site, app, github: gh, discovered: { github: ghFound, appLinks: appFound, docs: links.filter((l) => /docs|gitbook|whitepaper|litepaper/i.test(l)).slice(0, 5), social: links.filter((l) => /x\.com|twitter|t\.me|discord/i.test(l)).slice(0, 6) }, onchain, ghAddrHits };
  if (JSON_OUT) return console.log(JSON.stringify(report, (k, v) => (v instanceof Set ? [...v] : v), 1));
  const P = (...a) => console.log(...a);
  for (const s of [site, app].filter(Boolean)) {
    P(`\n=== ${s.label.toUpperCase()} ${s.url}  [${s.ok ? 'HTTP ' + s.status : 'FAILED ' + s.error}]  "${s.title}"`);
    P(`site builder: ${[...s.builders].join(', ') || '-'}   libs in bundle: ${[...s.web3].join(', ') || 'NONE'}   bundle ${(s.bundleBytes / 1024) | 0}KB`);
    P(`hosts: ${Object.entries(s.hosts).sort((a, b) => b[1] - a[1]).slice(0, 14).map(([h, n]) => `${h}(${n})`).join(' ')}`);
    P(`json APIs (${s.apis.size}):`); [...s.apis].slice(0, 20).forEach((x) => P('  ' + x));
    P(`wallet requests: ${[...new Set(s.walletReq)].join(', ') || 'none (dApp never asked the wallet anything)'}`);
    if (s.txRequests.length) P('!! dApp requested signatures/txs (captured+rejected):', JSON.stringify(s.txRequests).slice(0, 600));
    const rc = {}; s.rpcCalls.forEach((c) => { const k = `${c.m || 'eth_call'}${c.to ? ' ' + c.to : ''}`; rc[k] = (rc[k] || 0) + 1; });
    P(`on-chain reads: ${Object.keys(rc).length ? Object.entries(rc).slice(0, 15).map(([k, n]) => `${k} x${n}`).join(' | ') : 'NONE'}`);
    P(`chainIds referenced: ${[...s.chainIdsSeen].join(', ') || '-'}`);
    if (s.fake.size) { P(`fake/placeholder heuristics (noisy on big bundles — verify):`); [...s.fake].forEach((x) => P('  - ' + x)); }
    if (s.consoleErr.length) P(`console errors: ${s.consoleErr.slice(0, 5).join(' || ')}`);
    P(`visible text: ${s.text.slice(0, 900)}`);
  }
  P(`\n=== DISCOVERED  github: ${ghFound.join(' ') || '-'}  app: ${appFound.join(' ') || '-'}  docs: ${report.discovered.docs.join(' ') || '-'}`);
  P(`social: ${report.discovered.social.join(' ') || '-'}`);
  P(`\n=== ADDRESSES in site/app code (${addrs.size}):`);
  onchain.sort((x, y) => (y.called - x.called) || (y.on.length - x.on.length) || (y.freq - x.freq)).forEach((r) => P(`  ${r.called ? 'CALLED ' : '       '}${r.a} x${r.freq}  ${r.on.join(' ') || 'no code on eth/base/rh (EOA / other chain / junk)'}`));
  if (addrs.size > 40) P(`  (+${addrs.size - 40} more addresses in bundle not checked)`);
  if (gh) { P(`\n=== GITHUB ${gh.owner}`); for (const r of gh.repos) { if (r.error) { P(`  ${r.name}: HTTP ${r.error}`); continue; }
    P(`  ${r.name}${r.fork ? ' [FORK of ' + r.parent + ']' : ''}  created ${r.created} pushed ${r.pushed} ★${r.stars}  files ${r.files}${r.truncated ? '+' : ''}  tests ${r.tests}  backend ${r.hasBackend}`);
    P(`    langs ${r.langs || '-'} | contributors ${r.contributors} | commits(shown) ${r.commitsShown} ${r.firstShown}→${r.lastCommit}`);
    P(`    recent: ${r.commitMsgs.join(' ; ')}`); if (r.contracts.length) P(`    contracts: ${r.contracts.join(' ')}`);
    const hits = [...addrs].filter(() => false); } }
  P(`\nelapsed ${ms()}   screenshots: /tmp/claude-0/recon-site.png${app ? ' /tmp/claude-0/recon-app.png' : ''}`);
})();
